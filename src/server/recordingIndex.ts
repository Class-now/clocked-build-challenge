// Turns recordings/*.json into a TypeScript module, so a serverless function carries them with no
// file reads at run time. Only what the page shows goes in: the raw reply store stays in the file.
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import type { RecordedRun } from './contract.js';

export const GENERATED_PATH = 'src/server/recordings.generated.ts';

export function readRecordings(dir: string): RecordedRun[] {
  if (!existsSync(dir)) return [];
  const runs: RecordedRun[] = [];
  for (const name of readdirSync(dir).filter((n) => n.endsWith('.json')).sort()) {
    const file = JSON.parse(readFileSync(join(dir, name), 'utf8'));
    if (typeof file?.scenarioId !== 'string' || typeof file?.result?.verdict !== 'string') {
      throw new Error(`${name} is not a recording: it needs scenarioId and result.verdict.`);
    }
    runs.push({ scenarioId: file.scenarioId, recordedAt: String(file.recordedAt ?? ''), result: file.result });
  }
  return runs;
}

export function renderIndex(runs: RecordedRun[]): string {
  const entries = Object.fromEntries(runs.map((run) => [run.scenarioId, run]));
  return [
    '// Generated by scripts/index-recordings.ts from recordings/*.json. Do not edit.',
    "import type { RecordedRun } from './contract.js';",
    '',
    `export const RECORDINGS: Record<string, RecordedRun> = ${JSON.stringify(entries, null, 2)};`,
    '',
  ].join('\n');
}
